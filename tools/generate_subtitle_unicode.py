"""Generate the small bidi tables used only for legacy plain subtitle repair.

Usage: python tools/generate_subtitle_unicode.py <Unicode 17 UCD directory>
The directory must contain DerivedBidiClass.txt, BidiMirroring.txt and
BidiBrackets.txt (the dated filenames from the subtitle audit also work).
"""
from pathlib import Path
import re
import sys

root = Path(sys.argv[1])
names = 'L R AL EN AN ES ET CS NSM BN B S WS ON LRE LRO RLE RLO PDF LRI RLI FSI PDI'.split()
aliases = dict(Left_To_Right='L', Right_To_Left='R', Arabic_Letter='AL', European_Terminator='ET')

def read(name):
    path = next(root.glob(name + '*.txt'))
    return path.read_text(encoding='utf-8')

def span(value):
    values = value.strip().split('..')
    return int(values[0], 16), int(values[-1], 16)

classes = [0] * 0x110000
source = read('DerivedBidiClass')
for part in [re.findall(r'@missing:\s*([^;]+);\s*(\w+)', source),
             re.findall(r'^([0-9A-F.]+)\s*;\s*(\w+)', source, re.M)]:
    for value, kind in part:
        a, b = span(value)
        classes[a:b+1] = [names.index(aliases.get(kind, kind))] * (b-a+1)

out = ['// Generated by tools/generate_subtitle_unicode.py; Unicode 17.0.0.',
       '// Copyright 2025 Unicode, Inc. See THIRD_PARTY_NOTICES/Unicode.txt.',
       '// https://www.unicode.org/Public/17.0.0/ucd/',
       '// ignore_for_file: constant_identifier_names',
       '', 'enum SubtitleBidiClass { ' + ', '.join(names) + ' }', '',
       'SubtitleBidiClass subtitleBidiClass(int rune) {',
       '  var low = 0, high = _ranges.length ~/ 3;',
       '  while (low < high) {',
       '    final middle = (low + high) ~/ 2, offset = middle * 3;',
       '    if (rune < _ranges[offset]) { high = middle; }',
       '    else if (rune > _ranges[offset + 1]) { low = middle + 1; }',
       '    else { return SubtitleBidiClass.values[_ranges[offset + 2]]; }',
       '  }', '  return SubtitleBidiClass.L;', '}', '',
       'const _ranges = <int>[']
a = 0
for i in range(1, len(classes) + 1):
    if i == len(classes) or classes[i] != classes[a]:
        if classes[a] != 0:
            out.append(f'  0x{a:X}, 0x{i-1:X}, {classes[a]},')
        a = i
out.append('];')
for filename, name, bracket in [('BidiMirroring', 'subtitleBidiMirrors', False),
                                 ('BidiBrackets', 'subtitleBidiBrackets', True)]:
    out.extend(['', f'const {name} = <int, ' + ('(int, bool)' if bracket else 'int') + '>{'])
    for line in read(filename).splitlines():
        line = line.split('#')[0].strip()
        if not line:
            continue
        fields = [v.strip() for v in line.split(';')]
        value = f'(0x{fields[1]}, {str(fields[2] == "o").lower()})' if bracket else f'0x{fields[1]}'
        out.append(f'  0x{fields[0]}: {value},')
    out.append('};')
target = Path(__file__).resolve().parents[1] / 'lib/core/subtitle_unicode.dart'
target.write_text('\n'.join(out) + '\n', encoding='utf-8')
